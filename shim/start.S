/*
 * Boot shim entry: an arm64 Linux Image header so the bootloader treats us
 * like a kernel. Qualcomm ABL enters at EL1, MediaTek LK at EL1 or EL2; both
 * with the MMU and caches off and x0 = live device tree. EL2 is dropped to
 * EL1 before any C code runs, so everything below assumes EL1.
 */
	.section .text.head, "ax"
	.globl _head
_head:
	b	_start			/* code0 */
	.long	0			/* code1 */
	.quad	0			/* text_offset */
	.quad	_end			/* image_size (linked at 0) */
	.quad	0xa			/* flags: LE, 4K pages, place anywhere */
	.quad	0			/* res2 */
	.quad	0			/* res3 */
	.quad	0			/* res4 */
	.ascii	"ARM\x64"		/* magic */
	.long	0			/* res5 (PE offset) */

	.text
	.globl _start
_start:
	msr	daifset, #0xf
	mov	x19, x0			/* DTB pointer from the bootloader */
	mrs	x1, CurrentEL
	and	x1, x1, #0xc
	cmp	x1, #0x8
	b.eq	el2_setup
	b	el1_entry

/*
 * Entered at EL2 (MediaTek LK). Hand EL1 everything it needs and drop down:
 * the physical counter and timer must not trap, HCR_EL2.RW selects AArch64
 * at EL1, and stage-2 translation stays off so our physical accesses work.
 */
el2_setup:
	adr	x1, vectors		/* own vectors: LK's EL2 table is gone */
	msr	vbar_el2, x1
	isb
	mov	x1, #3			/* CNTHCTL_EL2: EL1PCTEN | EL1PCEN */
	msr	cnthctl_el2, x1
	msr	cntvoff_el2, xzr
	mov	x1, #0x33ff		/* CPTR_EL2: no FP/SIMD trap */
	msr	cptr_el2, x1
	msr	mdcr_el2, xzr
	mov	x1, #(1 << 31)		/* HCR_EL2.RW = 1, VM = 0 */
	msr	hcr_el2, x1
	isb
	mrs	x1, sctlr_el2
	bic	x1, x1, #1		/* SCTLR_EL2.M = 0 */
	msr	sctlr_el2, x1
	isb
	adr	x1, el1_entry
	msr	elr_el2, x1
	mov	x1, #0x3c5		/* EL1h, DAIF masked */
	msr	spsr_el2, x1
	eret

el1_entry:
	msr	spsel, #1
	/*
	 * Some bootloaders jump with their own identity map still on. The shim
	 * expects Device memory until it installs its tables, so turn the MMU
	 * (and caches) off first.
	 */
	mrs	x1, sctlr_el1
	tbz	x1, #0, 5f
	dsb	sy
	ic	iallu
	tlbi	vmalle1
	dsb	nsh
	isb
	bic	x1, x1, #1		/* M */
	bic	x1, x1, #4		/* C */
	bic	x1, x1, #(1 << 12)	/* I */
	msr	sctlr_el1, x1
	isb
	ic	iallu
	dsb	sy
	isb
5:
	adrp	x1, _stack_top
	add	x1, x1, :lo12:_stack_top
	mov	sp, x1
	adr	x1, vectors
	msr	vbar_el1, x1
	isb
	/* zero .bss */
	adrp	x1, _bss_start
	add	x1, x1, :lo12:_bss_start
	adrp	x2, _bss_end
	add	x2, x2, :lo12:_bss_end
1:	cmp	x1, x2
	b.hs	2f
	str	xzr, [x1], #8
	b	1b
2:	mov	x0, x19
#ifdef SHIM_RECOVERY_FALLBACK
	/* Diagnostic images embed stock Linux after the XNU payload. Recovery
	 * bypass happens before shim_main touches display/UFS/watchdog. Linux
	 * supports this EL1, MMU-off entry; x0 retains LK's live tree. */
	bl	shim_recovery_target
	cbz	x0, 6f
	mov	x4, x0
	mov	x0, x19
	mov	x1, xzr
	mov	x2, xzr
	mov	x3, xzr
	dsb	sy
	ic	iallu
	dsb	sy
	isb
	br	x4
6:	mov	x0, x19
#endif
	bl	shim_main
3:	wfe
	b	3b

/* PSCI CPU_ON target. x0 = context id = cpu index (1..7). */
	.globl secondary_entry
secondary_entry:
	msr	daifset, #0xf
	msr	spsel, #1
	adrp	x1, _sec_stacks
	add	x1, x1, :lo12:_sec_stacks
	add	x1, x1, x0, lsl #12
	add	x1, x1, #0x1000
	mov	sp, x1
	adr	x1, vectors
	msr	vbar_el1, x1
	isb
	bl	secondary_main
4:	wfe
	b	4b

/*
 * Exception vectors. Each slot stashes x29/x30, loads its slot number
 * and jumps to the common path, which saves x0-x28 and calls
 * exc_handler(slot, regs). IRQs return; everything else ends in the
 * on-screen panic.
 */
.macro vent slot
	.balign	0x80
	stp	x29, x30, [sp, #-16]!
	mov	x29, #\slot
	b	exc_common
.endm

	.balign	0x800
	.globl vectors
vectors:
	vent 0
	vent 1
	vent 2
	vent 3
	vent 4
	vent 5
	vent 6
	vent 7
	vent 8
	vent 9
	vent 10
	vent 11
	vent 12
	vent 13
	vent 14
	vent 15

exc_common:
	sub	sp, sp, #(30 * 8)
	stp	x0, x1, [sp, #0]
	stp	x2, x3, [sp, #16]
	stp	x4, x5, [sp, #32]
	stp	x6, x7, [sp, #48]
	stp	x8, x9, [sp, #64]
	stp	x10, x11, [sp, #80]
	stp	x12, x13, [sp, #96]
	stp	x14, x15, [sp, #112]
	stp	x16, x17, [sp, #128]
	stp	x18, x19, [sp, #144]
	stp	x20, x21, [sp, #160]
	stp	x22, x23, [sp, #176]
	stp	x24, x25, [sp, #192]
	stp	x26, x27, [sp, #208]
	str	x28, [sp, #224]
	mov	x0, x29
	mov	x1, sp
	bl	exc_handler
	ldp	x0, x1, [sp, #0]
	ldp	x2, x3, [sp, #16]
	ldp	x4, x5, [sp, #32]
	ldp	x6, x7, [sp, #48]
	ldp	x8, x9, [sp, #64]
	ldp	x10, x11, [sp, #80]
	ldp	x12, x13, [sp, #96]
	ldp	x14, x15, [sp, #112]
	ldp	x16, x17, [sp, #128]
	ldp	x18, x19, [sp, #144]
	ldp	x20, x21, [sp, #160]
	ldp	x22, x23, [sp, #176]
	ldp	x24, x25, [sp, #192]
	ldp	x26, x27, [sp, #208]
	ldr	x28, [sp, #224]
	add	sp, sp, #(30 * 8)
	ldp	x29, x30, [sp], #16
	eret
